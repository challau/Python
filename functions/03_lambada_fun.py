# lambda functions in python 
#  syntax: 

square = lambda x: x * x
'''
As good as writing 
def square(x):
    return x * x
'''
sum = lambda x,y : x + y
print(square(4))
print(sum(3,62))
'''
As good as writing 
def sum(x, y):
    return x + y
'''

